// Run by hand with `npm run concepts`, then review the output; the app never runs this.
import { readFileSync, writeFileSync } from 'node:fs'
import { tagItem } from '../src/search/concepts/direction.ts'
import { CONCEPTS } from '../src/search/concepts/seed.ts'
import {
  DIRECTIONS,
  type ConceptTag,
  type Concepts,
} from '../src/search/concepts/types.ts'

interface EffectText {
  name: string
  short_effect: string
  effect: string
}

const DATASET = new URL('../src/data/pokedex.json', import.meta.url)
const OUTPUT = new URL('../src/search/concepts/generated.ts', import.meta.url)

const { moves, abilities } = JSON.parse(readFileSync(DATASET, 'utf8')) as {
  moves: EffectText[]
  abilities: EffectText[]
}

const tags: ConceptTag[] = CONCEPTS.flatMap((concept) =>
  [
    ...moves.map((item) => ({ kind: 'move' as const, item })),
    ...abilities.map((item) => ({ kind: 'ability' as const, item })),
  ].flatMap(({ kind, item }) => {
    const tag = tagItem(item.short_effect, item.effect, concept)
    return tag ? [{ concept: concept.id, kind, name: item.name, ...tag }] : []
  }),
)

writeFileSync(
  OUTPUT,
  [
    '// Generated by `npm run concepts` (scripts/build-concepts.ts). Do not edit:',
    '// review it, and put corrections in corrections.ts.',
    "import type { Concepts } from './types.ts'",
    '',
    `export const GENERATED_TAGS: Concepts = ${JSON.stringify(groupTags(tags), null, 2)}`,
    '',
  ].join('\n'),
)

printSummary(tags)

function groupTags(all: ConceptTag[]): Concepts {
  return Object.fromEntries(
    CONCEPTS.map(({ id }) => [
      id,
      Object.fromEntries(
        DIRECTIONS.map((direction) => [
          direction,
          all
            .filter((t) => t.concept === id && t.direction === direction)
            .map(({ kind, name, evidence, source }) => ({
              kind,
              name,
              evidence,
              source,
            })),
        ]),
      ),
    ]),
  ) as Concepts
}

function printSummary(all: ConceptTag[]): void {
  console.log(
    `${all.length} tags written to src/search/concepts/generated.ts\n`,
  )
  console.table(
    Object.fromEntries(
      CONCEPTS.map(({ id }) => [
        id,
        Object.fromEntries(
          DIRECTIONS.map((direction) => [
            direction,
            all.filter((t) => t.concept === id && t.direction === direction)
              .length,
          ]),
        ),
      ]),
    ),
  )
  for (const direction of [
    'inflicts',
    'starts',
    'benefits',
    'unclear',
  ] as const) {
    console.log(`\n${direction.toUpperCase()}`)
    for (const t of all.filter((tag) => tag.direction === direction)) {
      console.log(
        `  ${t.concept.padEnd(10)} ${t.kind.padEnd(8)} ${t.name.padEnd(16)} ${t.evidence}`,
      )
    }
  }
}
